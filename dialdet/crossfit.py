"""Merge two audited cross-fit halves before computing the dataset metric."""
from pathlib import Path
import json
import shutil
from .data import manifest_document, atomic_json, sha256_file
from .artifacts import relative_artifact


def merge_runs(manifests, prediction_dirs, output):
    if len(manifests) != 2 or len(prediction_dirs) != 2:
        raise ValueError("Exactly two complementary cross-fit halves are required")
    docs = [manifest_document(p) for p in manifests]
    if docs[0]["dataset"] != docs[1]["dataset"]:
        raise ValueError("Cross-fit folds must belong to the same detection dataset")
    if {doc.get("fold") for doc in docs} != {0, 1}:
        raise ValueError("Expected fold0 and fold1 generated by make-crossfit")
    if any(doc.get("protocol") != "public_checkpoint_crossfit" for doc in docs):
        raise ValueError("Expected the documented public-checkpoint cross-fit protocol")
    if docs[0].get("source_manifest_sha256") != docs[1].get("source_manifest_sha256"):
        raise ValueError("The folds originate from different candidate pools")
    output = Path(output)
    # The CLI writes its lifecycle marker before dispatching. It is not a
    # previous merge artifact; every other existing file still blocks reuse.
    if output.exists() and any(path.name != "RUN_STATUS.json" for path in output.iterdir()):
        raise FileExistsError("The cross-fit merge directory must be empty; choose a new path to avoid stale evidence")
    output.mkdir(parents=True, exist_ok=True)
    entries, merged, seen = [], [], set()
    expected_groups = None
    for doc, manifest, prediction_dir in zip(docs, manifests, prediction_dirs):
        manifest, prediction_dir = Path(manifest), Path(prediction_dir)
        audit = [entry for entry in doc["records"] if entry["role"] == "audit"]
        ids = {str(entry["image_id"]) for entry in audit}
        if ids & seen:
            raise ValueError("An image is audited in both cross-fit halves")
        seen.update(ids)
        for entry in audit:
            entries.append({**entry, "path": str((manifest.parent / entry["path"]).resolve())})
        rows = [json.loads(line) for line in (prediction_dir / "predictions.jsonl").read_text().splitlines() if line.strip()]
        if {str(row["image_id"]) for row in rows} != ids:
            raise ValueError("Prediction images differ from the fold's audit population")
        groups = {}
        for row in rows:
            key = (str(row["method"]), row["K"])
            group = groups.setdefault(key, set())
            if str(row["image_id"]) in group:
                raise ValueError("Duplicate cross-fit image/method/budget prediction")
            group.add(str(row["image_id"]))
        if any(population != ids for population in groups.values()):
            raise ValueError("Every cross-fit method/budget must cover its complete audit half")
        if expected_groups is None:
            expected_groups = set(groups)
        elif set(groups) != expected_groups:
            raise ValueError("Cross-fit halves have different method/budget groups")
        for row in rows:
            for key in ("evidence", "certificate", "policy"):
                if row.get(key):
                    source = relative_artifact(prediction_dir, row[key])
                    target = output / f"fold{doc['fold']}" / row[key]
                    target.parent.mkdir(parents=True, exist_ok=True)
                    if not target.exists():
                        shutil.copy2(source, target)
                    elif sha256_file(source) != sha256_file(target):
                        raise ValueError("Conflicting cross-fit artifact paths")
                    row[key] = str(target.relative_to(output))
            merged.append(row)
    original_ids = {str(e["image_id"]) for e in docs[0]["records"]}
    if seen != original_ids:
        raise ValueError("The two audit halves do not cover the full source population")
    manifest = output / "manifest.json"
    retained = {key: docs[0][key] for key in ("annotations_file", "quality_mode", "num_classes", "person_class_id")
                if key in docs[0] and docs[0].get(key) == docs[1].get(key)}
    atomic_json(manifest, {"schema_version": 1, "dataset": docs[0]["dataset"], **retained,
               "protocol": "public_checkpoint_crossfit_union", "risk_eligible": False, "records": entries})
    with (output / "predictions.jsonl").open("w") as stream:
        for row in merged:
            stream.write(json.dumps(row, sort_keys=True, allow_nan=False) + "\n")
    result = {"manifest": str(manifest.resolve()), "predictions": str((output / "predictions.jsonl").resolve()),
              "audited_images": len(seen), "dataset": docs[0]["dataset"],
              "is_synthetic": (True if docs[0]["dataset"].startswith("synthetic") else
                               False if docs[0]["dataset"] in ("coco", "crowdhuman", "citypersons") else None),
              "note": "Evaluate this held-out union with the dataset's evaluator; do not average the two fold APs or miss rates."}
    atomic_json(output / "MERGE.json", result)
    return result
